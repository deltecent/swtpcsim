* General equates used in NEWDISK

FIRST	EQU	$0101		FIRST USED SECTOR
FCS	EQU	30		FCB CURRENT SECTOR
FSB	EQU	64		FCB SECTOR BUFFER
IRS	EQU	16		INFO RECORD START
AVLP	EQU	FSB+IRS+13
DIRSEC	EQU	5		FIRST DIR. SECTOR
RDSS	EQU	9		READ SS FMS CODE
WTSS	EQU	10		WRITE SS FMS CODE

* Work space where one track of data is setup

WORK	EQU	$0100		WORK SPACE
TKSZ	EQU	3008		SIZE OF SD WORK BUFFER
SWKEND	EQU	TKSZ+WORK

TOT35	EQU	340		TOTAL SECTORS SINGLE SIDED
TOT40	EQU	390		TOTAL SECTORS 40 TRACK SS
TOTDS	EQU	780		TOTAL SECTORS 40 TRACK DS

MAXS0	EQU	10		SD MAX SIDE 0 SECTORS
MAXS1	EQU	20		SD MAX SIDE 1 SECTORS

* FLEX LOCATIONS

SSTACK	EQU	$A07F
SMONTH	EQU	$AC0E		DOS DATE
SDAYMN	EQU	$AC0F
SYEARN	EQU	$AC10

* FLEX ROUTINES EQUATES

WARMST	EQU	$AD03
GETCHR	EQU	$AD15
PUTCHR	EQU	$AD18
INBUFF	EQU	$AD1B
PSTRNG	EQU	$AD1E
PRCRLF	EQU	$AD24
GETFIL	EQU	$AD2D
OUTDEC	EQU	$AD39
OUTHEX	EQU	$AD3C
GETHEX	EQU	$AD42
INDECM	EQU	$AD48
FMSCAL	EQU	$B406

* DISK DRIVER ROUTINES

DWRITE	EQU	$BE83		WRITE A SINGLE SECTOR
DRSTOR	EQU	$BE89		RESTORE HEAD
DSEEK	EQU	$0000		SEEK TO TRACK

DRVREG	EQU	$8014		FDC DRIVE SELECT
COMREG	EQU	$8018		FDC COMMAND REG
TRKREG	EQU	$8019		FDC TRACK REG
SECREG	EQU	$801A		FDC SECTOR REG
DATREG	EQU	$801B		FDC DATA REG
DRQREG	EQU	$801E		FDC STATUS DRQ-INTRQ

	ORG	$A100

