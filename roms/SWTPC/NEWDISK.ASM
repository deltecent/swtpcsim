* WRITE TRACK ROUTINE
* FOR SWTP DC1

* COMMANDS
WTCMD	EQU	$F4		WRITE TRACK
SKCMD	EQU	$1B		SEEK COMMAND

WRTTRK	LDAA	DRN		A=DRIVE NUMBER, SIDE 0
	TST	SIDE		SIDE 0 OR 1?
	BEQ	WRTTR1		SIDE 0
	ORAA	#$40		SET SIDE 1 BIT

WRTTR1	STAA	DRVREG		SELECT SIDE 0 OR 1
	JSR	DELAY
	LDX	#WORK		POINT TO DATA
	LDAA	#WTCMD		WRITE TRACK
	STAA	COMREG		ISSUE COMMAND
	JSR	DELAY

WRTTR2	LDAA	COMREG		CHECK STATUS
	BITA	#$02		IS FDC READY FOR DATA
	BNE	WRTTR4		DRQ READY
	BITA	#$01		IS FDC BUSY
	BNE	WRTTR2		LOOP UNTIL SO
	BRA	WRTTR8		REPORT ERROR

WRTTR4	LDAA	0,X		GET DATA BYTE
	STAA	DATREG		SEND TO DISK
	INX
	CPX	#SWKEND
	BNE	WRTTR2
	BSR	WAIT
WRTTR8	RTS

SEEK	STAA	DATREG
	LDAA	#SKCMD
	STAA	COMREG
	JSR	DELAY

WAIT	LDAA	COMREG
	BITA	#$01
	BNE	WAIT
	RTS

DELAY	JSR	DELAY2
DELAY2	JSR	DELAY4
DELAY4	RTS

