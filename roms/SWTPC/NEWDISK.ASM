* NEWDISK
*
* Original disassembled by Michael Holley 3 Dec 1981
* Disk formatting program for FLEX 2.0 or 3.0
* This version is for SWTPC 6800
*
* Ver    Date     Description
* 1.0  11/14/20   M. Douglas, support 35 and 40 track single-sided
*		  and 40 track double-sided formats. Also added a
*		  one second motor start-up delay to prevent track
*		  zero failures.
*
* 1.1   2/14/22	  M. Douglas, fix sector link error for double-
*		  sided disks.
*

* TEMPORARY STORAGE

	ORG	$20
